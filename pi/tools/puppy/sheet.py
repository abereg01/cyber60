"""Pack the rendered puppy frames into the sprite sheet the screen loads.

Reads <frames>/anims.json and the frames puppy.py rendered (at SS times their
cell size), scales each down to its cell and writes
  dog.png        one strip per animation, frames left to right (RGBA):
                 the sprites (DOG_CELL_W x DOG_CELL_H), then the scenes
                 (DOG_SCENE_W x DOG_SCENE_H), then one strip of effects
                 (DOG_FX_W x DOG_FX_H)
  dog_sheet.h    its layout for pet.c
  preview.png    the whole sheet at 2x on the BASE white and the GAMING night
                 ground, for eyeballing (not used by the build)

Usage: python3 sheet.py <frames dir> <dog.png> <dog_sheet.h> <preview.png>
"""

import json
import os
import sys

from PIL import Image

frames, sheet_path, header_path, preview_path = sys.argv[1:5]
meta = json.load(open(os.path.join(frames, "anims.json")))
sprite, scenes, fx = meta["sprite"], meta["scene"], meta["fx"]


missing = [f"{a['name']}_{i}.png" for g in (sprite, scenes) for a in g["anims"] for i in range(a["frames"])]
missing = [n for n in missing + [f"fx_{n}.png" for n in fx["names"]] if not os.path.exists(os.path.join(frames, n))]
if missing:
    sys.exit(f"not packed: {len(missing)} frames missing ({missing[0]}, ...); run gen-dog.sh without a prefix")


def load(name, cell):
    big = Image.open(os.path.join(frames, name)).convert("RGBa")
    return big.resize(tuple(cell), Image.LANCZOS).convert("RGBA")


# Strips, top to bottom: (group, anim, cell, y).
strips, y = [], 0
for group in (sprite, scenes):
    for a in group["anims"]:
        strips.append((group, a, group["cell"], y))
        y += group["cell"][1]
fx_y = y
height = y + fx["cell"][1]
width = max(max(a["frames"] * g["cell"][0] for a in g["anims"]) for g in (sprite, scenes))
width = max(width, len(fx["names"]) * fx["cell"][0])

sheet = Image.new("RGBA", (width, height), (0, 0, 0, 0))
for group, a, cell, top in strips:
    for i in range(a["frames"]):
        sheet.paste(load(f"{a['name']}_{i}.png", cell), (i * cell[0], top))
for i, n in enumerate(fx["names"]):
    sheet.paste(load(f"fx_{n}.png", fx["cell"]), (i * fx["cell"][0], fx_y))
sheet.save(sheet_path, optimize=True)


def table(prefix, group):
    return [f"    [{prefix}{a['name'].upper()}] = {{{top}, {a['frames']}, {a['fps']}, "
            f"{'true' if a['loop'] else 'false'}}},"
            for g, a, cell, top in strips if g is group]


lines = [
    "/* Generated by pi/tools/puppy/sheet.py. Do not edit; rerun pi/tools/gen-dog.sh. */",
    "#pragma once",
    "",
    "#include <stdbool.h>",
    "#include <stdint.h>",
    "",
    "// dog.png: one strip per animation, frames left to right. Sprites are",
    "// DOG_CELL_W x DOG_CELL_H with the ground under the puppy's middle at",
    "// (DOG_CELL_W / 2, DOG_FEET_Y), rendered facing right. Scenes fill the whole",
    "// square (DOG_SCENE_W x DOG_SCENE_H). The effects strip is at DOG_FX_Y.",
    f"#define DOG_CELL_W {sprite['cell'][0]}",
    f"#define DOG_CELL_H {sprite['cell'][1]}",
    f"#define DOG_FEET_Y {sprite['feet']}",
    f"#define DOG_SCENE_W {scenes['cell'][0]}",
    f"#define DOG_SCENE_H {scenes['cell'][1]}",
    f"#define DOG_FX_W {fx['cell'][0]}",
    f"#define DOG_FX_H {fx['cell'][1]}",
    f"#define DOG_FX_Y {fx_y}",
    f"#define DOG_SHEET_W {width}",
    f"#define DOG_SHEET_H {height}",
    "",
    "enum dog_anim {",
    *[f"    DOG_{a['name'].upper()}," for a in sprite["anims"]],
    "    DOG_ANIM_COUNT,",
    "};",
    "",
    "enum dog_scene {",
    *[f"    DOG_SCENE_{a['name'].upper()}," for a in scenes["anims"]],
    "    DOG_SCENE_COUNT,",
    "};",
    "",
    "enum dog_fx {",
    *[f"    DOG_FX_{n.upper()}," for n in fx["names"]],
    "    DOG_FX_COUNT,",
    "};",
    "",
    "struct dog_strip {",
    "    uint16_t y; // top of the strip in dog.png",
    "    uint8_t frames, fps;",
    "    bool loop;",
    "};",
    "",
    "static const struct dog_strip dog_anims[DOG_ANIM_COUNT] = {",
    *table("DOG_", sprite),
    "};",
    "",
    "static const struct dog_strip dog_scenes[DOG_SCENE_COUNT] = {",
    *table("DOG_SCENE_", scenes),
    "};",
    "",
]
with open(header_path, "w") as f:
    f.write("\n".join(lines))

big = sheet.resize((sheet.width * 2, sheet.height * 2), Image.LANCZOS)
out = Image.new("RGB", (big.width * 2 + 16, big.height), (0x80, 0x80, 0x80))
for i, bg in enumerate([(0xFF, 0xFF, 0xFF), (0x16, 0x21, 0x2A)]):
    pane = Image.new("RGB", big.size, bg)
    pane.paste(big, (0, 0), big)
    out.paste(pane, (i * (big.width + 16), 0))
out.save(preview_path)
