"""Pack the rendered puppy frames into the sprite sheet the screen loads.

Reads <frames>/anims.json and <frames>/<anim>_<i>.png (from puppy.py, rendered
at SS times the cell size), scales each frame down to the cell and writes
  dog.png        one row per animation, frames left to right (RGBA)
  dog_sheet.h    its layout for pet.c
  preview.png    every frame at 2x on the BASE white and the GAMING night
                 ground, for eyeballing (not used by the build)

Usage: python3 sheet.py <frames dir> <dog.png> <dog_sheet.h> <preview.png>
"""

import json
import os
import sys

from PIL import Image

COLS = 8

frames, sheet_path, header_path, preview_path = sys.argv[1:5]
meta = json.load(open(os.path.join(frames, "anims.json")))
cw, ch = meta["cell"]
anims = meta["anims"]
assert max(a["frames"] for a in anims) <= COLS

sheet = Image.new("RGBA", (cw * COLS, ch * len(anims)), (0, 0, 0, 0))
for r, a in enumerate(anims):
    for i in range(a["frames"]):
        big = Image.open(os.path.join(frames, f"{a['name']}_{i}.png")).convert("RGBa")
        sheet.paste(big.resize((cw, ch), Image.LANCZOS).convert("RGBA"), (i * cw, r * ch))
sheet.save(sheet_path, optimize=True)

lines = [
    "/* Generated by pi/tools/puppy/sheet.py. Do not edit; rerun pi/tools/gen-dog.sh. */",
    "#pragma once",
    "",
    "#include <stdbool.h>",
    "#include <stdint.h>",
    "",
    "// dog.png: one row per animation, frames left to right, each a",
    "// DOG_CELL_W x DOG_CELL_H cell with the ground under the puppy's middle at",
    "// (DOG_CELL_W / 2, DOG_FEET_Y). Rendered facing right.",
    f"#define DOG_CELL_W {cw}",
    f"#define DOG_CELL_H {ch}",
    f"#define DOG_FEET_Y {meta['feet']}",
    "",
    "enum dog_anim {",
    *[f"    DOG_{a['name'].upper()}," for a in anims],
    "    DOG_ANIM_COUNT,",
    "};",
    "",
    "static const struct {",
    "    uint8_t frames, fps;",
    "    bool loop;",
    "} dog_anims[DOG_ANIM_COUNT] = {",
    *[f"    [DOG_{a['name'].upper()}] = {{{a['frames']}, {a['fps']}, {'true' if a['loop'] else 'false'}}},"
      for a in anims],
    "};",
    "",
]
with open(header_path, "w") as f:
    f.write("\n".join(lines))

big = sheet.resize((sheet.width * 2, sheet.height * 2), Image.LANCZOS)
out = Image.new("RGB", (big.width * 2 + 16, big.height), (0x80, 0x80, 0x80))
for i, bg in enumerate([(0xFF, 0xFF, 0xFF), (0x16, 0x21, 0x2A)]):
    pane = Image.new("RGB", big.size, bg)
    pane.paste(big, (0, 0), big)
    out.paste(pane, (i * (big.width + 16), 0))
out.save(preview_path)
