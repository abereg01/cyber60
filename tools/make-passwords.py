#!/usr/bin/env python3
"""Write config/secrets/passwords.dtsi (gitignored, mode 600) with the two
password macros &pw1 and &pw2.

The passwords are typed at a hidden prompt, so they never show on screen, in
shell history or in a chat. A macro sends key positions, not characters, so it
has to know which keyboard layout the computer is in when you trigger it:

    python3 tools/make-passwords.py --layout us     # computer set to English (US)
    python3 tools/make-passwords.py --layout sv     # computer set to Swedish

Add --enter to press Enter after each password. Leave a password empty to
keep that macro as a placeholder that types nothing. Then build locally with
tools/build.sh dongle.
"""

import argparse
import getpass
import os
import string
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
OUT = os.path.join(HERE, "..", "config", "secrets", "passwords.dtsi")

# Fast but not instant: every key gets a press and a release report, so
# repeated characters ("ss") don't merge. ~8 ms per character.
TAP_MS = 4
WAIT_MS = 4

LETTERS = {c: [c.upper()] for c in string.ascii_lowercase}
LETTERS.update({c: [f"LS({c})"] for c in string.ascii_uppercase})
DIGITS = {str(d): [f"N{d}"] for d in range(10)}

US = {
    **LETTERS, **DIGITS, " ": ["SPACE"],
    "!": ["LS(N1)"], "@": ["LS(N2)"], "#": ["LS(N3)"], "$": ["LS(N4)"],
    "%": ["LS(N5)"], "^": ["LS(N6)"], "&": ["LS(N7)"], "*": ["LS(N8)"],
    "(": ["LS(N9)"], ")": ["LS(N0)"],
    "-": ["MINUS"], "_": ["LS(MINUS)"], "=": ["EQUAL"], "+": ["LS(EQUAL)"],
    "[": ["LBKT"], "{": ["LS(LBKT)"], "]": ["RBKT"], "}": ["LS(RBKT)"],
    "\\": ["BSLH"], "|": ["LS(BSLH)"], ";": ["SEMI"], ":": ["LS(SEMI)"],
    "'": ["SQT"], '"': ["LS(SQT)"], ",": ["COMMA"], "<": ["LS(COMMA)"],
    ".": ["DOT"], ">": ["LS(DOT)"], "/": ["FSLH"], "?": ["LS(FSLH)"],
    "`": ["GRAVE"], "~": ["LS(GRAVE)"],
}

# Swedish (Windows/Linux "se"). Keycode names are the US ones for the same key.
# ^ ~ ` ´ ¨ are dead keys, so they need a Space after them.
SV = {
    **LETTERS, **DIGITS, " ": ["SPACE"],
    "!": ["LS(N1)"], '"': ["LS(N2)"], "#": ["LS(N3)"], "¤": ["LS(N4)"],
    "%": ["LS(N5)"], "&": ["LS(N6)"], "/": ["LS(N7)"], "(": ["LS(N8)"],
    ")": ["LS(N9)"], "=": ["LS(N0)"],
    "@": ["RA(N2)"], "£": ["RA(N3)"], "$": ["RA(N4)"], "€": ["RA(N5)"],
    "{": ["RA(N7)"], "[": ["RA(N8)"], "]": ["RA(N9)"], "}": ["RA(N0)"],
    "+": ["MINUS"], "?": ["LS(MINUS)"], "\\": ["RA(MINUS)"],
    "'": ["NUHS"], "*": ["LS(NUHS)"],
    ",": ["COMMA"], ";": ["LS(COMMA)"], ".": ["DOT"], ":": ["LS(DOT)"],
    "-": ["FSLH"], "_": ["LS(FSLH)"],
    "<": ["NUBS"], ">": ["LS(NUBS)"], "|": ["RA(NUBS)"],
    "å": ["LBKT"], "Å": ["LS(LBKT)"], "ä": ["SQT"], "Ä": ["LS(SQT)"],
    "ö": ["SEMI"], "Ö": ["LS(SEMI)"], "§": ["GRAVE"], "½": ["LS(GRAVE)"],
    "^": ["LS(RBKT)", "SPACE"], "~": ["RA(RBKT)", "SPACE"], "¨": ["RBKT", "SPACE"],
    "`": ["LS(EQUAL)", "SPACE"], "´": ["EQUAL", "SPACE"],
}


def keycodes(password, table):
    codes = []
    for ch in password:
        if ch not in table:
            sys.exit(f"Can't type {ch!r} in this layout; nothing written.")
        codes += table[ch]
    return codes


def macro(name, codes):
    bindings = " ".join(f"&kp {c}" for c in codes) if codes else "&none"
    return f"""        {name}: {name} {{
            compatible = "zmk,behavior-macro";
            #binding-cells = <0>;
            wait-ms = <{WAIT_MS}>;
            tap-ms = <{TAP_MS}>;
            bindings = <{bindings}>;
        }};
"""


def ask(label):
    while True:
        first = getpass.getpass(f"{label} (empty = placeholder): ")
        if first == getpass.getpass(f"{label} again: "):
            return first
        print("They didn't match, try again.")


def main():
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--layout", choices=["us", "sv"], required=True,
                        help="keyboard layout the computer is in when the macro runs")
    parser.add_argument("--enter", action="store_true", help="press Enter after each password")
    args = parser.parse_args()
    table = US if args.layout == "us" else SV

    macros = ""
    for name in ("pw1", "pw2"):
        password = ask(f"Password for &{name}")
        codes = keycodes(password, table)
        if codes and args.enter:
            codes.append("RET")
        macros += macro(name, codes)

    os.makedirs(os.path.dirname(OUT), mode=0o700, exist_ok=True)
    fd = os.open(OUT, os.O_WRONLY | os.O_CREAT | os.O_TRUNC, 0o600)
    with os.fdopen(fd, "w") as f:
        f.write(f"/* Generated by tools/make-passwords.py (layout: {args.layout}). "
                "Gitignored: never commit. */\n\n/ {\n    macros {\n" + macros + "    };\n};\n")
    os.chmod(OUT, 0o600)
    print(f"Wrote {os.path.normpath(OUT)}. Build with: tools/build.sh dongle")


if __name__ == "__main__":
    main()
